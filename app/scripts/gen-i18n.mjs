#!/usr/bin/env node
/**
 * Builds src/i18n/chart-names.generated.ts from the chart translations in
 * ../templates/i18n/{en,de,id,ar}.toml, so the account names the app shows
 * come from the same files the Rust side imports (one source of truth).
 *
 * Run with `bun run i18n:gen`. i18n.test.ts fails when the committed file is
 * stale. The TOML subset is the one those files use: flat `"key" = "value"`
 * lines, comments, and blank lines.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const LANGUAGES = ['en', 'de', 'id', 'ar'];
const LINE = /^"([^"]+)"\s*=\s*"((?:[^"\\]|\\.)*)"\s*$/;

/** Parses one catalogue file. Throws on any line that is neither a comment, blank, nor a key. */
export function parseCatalogue(text, source) {
  const entries = {};
  text.split('\n').forEach((raw, index) => {
    const line = raw.trim();
    if (line === '' || line.startsWith('#')) return;
    const match = LINE.exec(line);
    if (!match) throw new Error(`${source}:${index + 1}: not a flat quoted key: ${line}`);
    if (Object.hasOwn(entries, match[1])) throw new Error(`${source}:${index + 1}: duplicate key ${match[1]}`);
    entries[match[1]] = match[2].replace(/\\(.)/g, '$1');
  });
  return entries;
}

/** Renders the generated module from the four catalogues. */
export function renderChartNames(catalogues) {
  const body = LANGUAGES.map((code) => `  ${code}: ${JSON.stringify(catalogues[code], null, 2).replace(/\n/g, '\n  ')},`).join('\n');
  return `// Generated by scripts/gen-i18n.mjs from templates/i18n/*.toml. Do not edit.\nexport const CHART_NAMES = {\n${body}\n} as const;\n`;
}

/** Loads the four catalogues from the repository's templates directory. */
export function loadCatalogues(templatesDir) {
  const catalogues = {};
  for (const code of LANGUAGES) {
    const file = resolve(templatesDir, 'i18n', `${code}.toml`);
    catalogues[code] = parseCatalogue(readFileSync(file, 'utf8'), file);
  }
  return catalogues;
}

export const OUTPUT = resolve(here, '..', 'src', 'i18n', 'chart-names.generated.ts');
export const TEMPLATES = resolve(here, '..', '..', 'templates');

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT, renderChartNames(loadCatalogues(TEMPLATES)));
  console.log(`wrote ${OUTPUT}`);
}
