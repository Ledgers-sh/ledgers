//! The Command trait: the unified interface for all operations.
//!
//! Every operation is one Command, with a name, input/output schemas,
//! a required policy tier, and methods to preview and plan.

use crate::error::CommandError;
use crate::exec::ExecToken;
use crate::journal_preview::JournalPreview;
use cratefield_core::{Database, Statement};
use schemars::JsonSchema;
use serde::{Deserialize, Serialize};

/// The result of planning a command: the SQL statements to execute, the
/// output to return, and the object ids touched (for the audit event).
#[derive(Clone, Debug)]
pub struct Plan<Output> {
    /// The SQL statements to execute in the batch.
    pub statements: Vec<Statement>,
    /// The output the command returns to the caller.
    pub output: Output,
    /// The object ids this command touched (e.g., entry numbers, journal ids).
    pub objects: Vec<String>,
}

impl<Output> Plan<Output> {
    /// Creates a plan with no statements (e.g., idempotent replay, read-only).
    pub fn with_output(output: Output) -> Self {
        Plan {
            statements: vec![],
            output,
            objects: vec![],
        }
    }
}

/// Context passed to preview and plan: company, request, event ids.
#[derive(Clone, Debug)]
pub struct CommandContext {
    /// The company id the command runs for.
    pub company_id: String,
    /// A request id (for tracing).
    pub request_id: String,
    /// The audit event id (generated by the executor, passed to plan).
    pub event_id: String,
    /// ISO 8601 UTC timestamp (now).
    pub now: String,
}

/// The Command trait: define the name, input/output, tier, and the
/// operations that preview and plan the command.
///
/// All async methods use `async_trait` with `?Send` (wasm-clean for
/// Workers runtime, and matching the harness's `Database` port).
#[async_trait::async_trait(?Send)]
pub trait Command: Send + Sync {
    /// The command's resource and verb (e.g., `"bills.match"`, `"journal.post"`).
    /// Must be lowercase, alphanumeric and underscores/dashes, like `"resource.verb"` or
    /// `"resource.sub_resource.verb"`.
    const NAME: &'static str;

    /// The policy tier required to run this command.
    const TIER: crate::auth::Tier;

    /// True if only humans may run this command.
    const HUMAN_ONLY: bool = false;

    /// True if this command supports dry-run mode.
    const SUPPORTS_DRY_RUN: bool = false;

    /// True if this command is idempotent (same input → same output, safe to replay).
    const IDEMPOTENT: bool = false;

    /// The input field that becomes the HTTP path id (e.g., "id" for `/v1/bills/{id}/match`).
    /// None means the command is not indexed by a path parameter.
    const TARGET: Option<&'static str> = None;

    /// The input type: what the caller sends.
    type Input: Serialize + for<'de> Deserialize<'de> + JsonSchema + Send + Sync + std::fmt::Debug;

    /// The output type: what the command returns.
    type Output: Serialize + JsonSchema + Send + Sync;

    /// Previews what this command would do: the debit and credit lines,
    /// per-currency totals, and whether it moves money.
    ///
    /// A preview is required for policy decision-making and required for
    /// dry-run support. Empty preview means the command moves no money.
    ///
    /// # Errors
    /// Returns a `CommandError` if the preview cannot be computed (e.g., invalid input).
    async fn preview(
        &self,
        db: &dyn Database,
        ctx: &CommandContext,
        input: &Self::Input,
    ) -> Result<JournalPreview, CommandError>;

    /// Plans what this command will do: the SQL statements to execute,
    /// the output, and the objects touched (for audit).
    ///
    /// The token proves this is inside the executor (re-planning on retry
    /// is safe). Called only after preview succeeded and policy allowed.
    /// Plans must be re-runnable: the executor may re-plan on chain-fork
    /// retry.
    ///
    /// # Errors
    /// Returns a `CommandError` if planning fails (rare, since preview already
    /// validated the input).
    async fn plan(
        &self,
        token: &ExecToken,
        db: &dyn Database,
        ctx: &CommandContext,
        input: &Self::Input,
    ) -> Result<Plan<Self::Output>, CommandError>;
}
